"""
GRIDSEC — Physics Validation & Conservation-Law Verification Layer.
Independently verifies whether every simulated electrical state produced by the AC power-flow solver
satisfies fundamental power-system constraints:
1. Kirchhoff's Current Law (KCL) / Active & Reactive Power Conservation (P_gen ≈ P_load + P_loss, Q_gen ≈ Q_load + Q_loss)
2. Bus Voltage Limits (Nominal 0.90 - 1.10 pu, Critical <0.85 / >1.15 pu)
3. Transmission Line Thermal Loading Constraints (<= 100.0%)
4. Transformer Rating and Tap Position Constraints (tap_min <= tap <= tap_max)
5. Generator Active & Reactive Operational Limits (Pmin <= P <= Pmax, Qmin <= Q <= Qmax)
6. Numerical Sanity (Convergence, Finite Real Values, NaN/Inf Protection)

Strictly Read-Only: Does not alter solver results, mutate database state, or execute autonomous control.
"""

import math
from enum import Enum
from datetime import datetime
from typing import Dict, Any, List, Optional, Tuple, Union
from pydantic import BaseModel, Field

from app.power.models import PowerFlowResult, LineResult, TransformerResult, BusResult, PowerBalance, GeneratorModel


class ThresholdSource(str, Enum):
    PROJECT_DEFAULT = "PROJECT_DEFAULT"      # Project-defined engineering assumption (controllable simulation threshold)
    MODEL_DERIVED = "MODEL_DERIVED"          # Derived directly from benchmark/substation physical equipment ratings
    STANDARD_DERIVED = "STANDARD_DERIVED"    # Derived from formal grid codes (e.g. Indian Electricity Grid Code / CEA)


class VoltageClassification(str, Enum):
    NORMAL = "NORMAL"                        # Nominal operational band (0.90 pu <= V <= 1.10 pu)
    VOLTAGE_VIOLATION = "VOLTAGE_VIOLATION"  # Warning band (0.85 <= V < 0.90 pu or 1.10 < V <= 1.15 pu)
    CRITICAL_VOLTAGE = "CRITICAL_VOLTAGE"    # Emergency / severe band (V < 0.85 pu or V > 1.15 pu)


class PhysicsViolationType(str, Enum):
    POWER_BALANCE_VIOLATION = "POWER_BALANCE_VIOLATION"
    VOLTAGE_VIOLATION = "VOLTAGE_VIOLATION"
    VOLTAGE_UNDERVOLTAGE = "VOLTAGE_UNDERVOLTAGE"
    VOLTAGE_OVERVOLTAGE = "VOLTAGE_OVERVOLTAGE"
    LINE_THERMAL_LIMIT = "LINE_THERMAL_LIMIT"
    LINE_OVERLOAD = "LINE_OVERLOAD"
    TRANSFORMER_LIMIT = "TRANSFORMER_LIMIT"
    TRANSFORMER_OVERLOAD = "TRANSFORMER_OVERLOAD"
    TRANSFORMER_TAP_INVALID = "TRANSFORMER_TAP_INVALID"
    GENERATOR_P_LIMIT = "GENERATOR_P_LIMIT"
    GENERATOR_Q_LIMIT = "GENERATOR_Q_LIMIT"
    SOLVER_DIVERGENCE = "SOLVER_DIVERGENCE"
    NUMERICAL_INVALID_STATE = "NUMERICAL_INVALID_STATE"


class PhysicsViolationRecord(BaseModel):
    """
    Standardized physical constraint breach record generated by PhysicsValidator.
    """
    violation_type: str
    element_id: str
    element_type: str  # SYSTEM, BUS, LINE, TRANSFORMER, GENERATOR
    observed_value: float
    limit_value: Union[float, str]
    violation_amount: float
    unit: str = "%"
    severity: str = "WARNING"  # CRITICAL, WARNING, INFO
    threshold_source: str = ThresholdSource.PROJECT_DEFAULT.value
    rule_name: str = ""
    provenance: str = "SOLVER_DERIVED"
    description: str
    step: int = 0
    simulation_id: Optional[str] = None
    cascade_id: Optional[str] = None
    timestamp: str = Field(default_factory=lambda: datetime.utcnow().isoformat())


class PhysicsValidationMetrics(BaseModel):
    """
    Quantitative electrical energy conservation metrics computed during validation.
    """
    total_generation_p_mw: float = 0.0
    total_load_p_mw: float = 0.0
    total_losses_p_mw: float = 0.0
    active_power_balance_error_mw: float = 0.0
    system_active_balance_residual: float = 0.0
    total_generation_q_mvar: float = 0.0
    total_load_q_mvar: float = 0.0
    total_losses_q_mvar: float = 0.0
    reactive_power_balance_error_mvar: float = 0.0
    system_reactive_balance_residual: float = 0.0
    max_line_loading_pct: float = 0.0
    max_transformer_loading_pct: float = 0.0
    min_bus_voltage_pu: float = 1.0
    max_bus_voltage_pu: float = 1.0
    max_nodal_p_residual_mw: float = 0.0
    maximum_nodal_p_residual: float = 0.0
    maximum_nodal_q_residual: float = 0.0
    voltage_classification: str = VoltageClassification.NORMAL.value
    violated_buses: List[str] = Field(default_factory=list)
    active_power_balance_passed: bool = True
    reactive_power_balance_passed: bool = True
    nodal_balance_passed: bool = True


class PhysicsValidationTolerances(BaseModel):
    """
    Engineering tolerances for physics validation checks.
    """
    active_power_balance_tol_mw: float = 1.0        # Max allowable active power mismatch (MW) [PROJECT_DEFAULT]
    reactive_power_balance_tol_mvar: float = 2.0    # Max allowable reactive power mismatch (MVAr) [PROJECT_DEFAULT]
    nodal_p_balance_tol_mw: float = 1.0             # Max allowable nodal active power mismatch (MW) [PROJECT_DEFAULT]
    nodal_q_balance_tol_mvar: float = 2.0           # Max allowable nodal reactive power mismatch (MVAr) [PROJECT_DEFAULT]
    voltage_min_nominal_pu: float = 0.90             # Low voltage warning threshold [PROJECT_DEFAULT / CEA Nominal]
    voltage_max_nominal_pu: float = 1.10             # High voltage warning threshold [PROJECT_DEFAULT / CEA Nominal]
    voltage_min_critical_pu: float = 0.85            # Severe undervoltage threshold [PROJECT_DEFAULT]
    voltage_max_critical_pu: float = 1.15            # Severe overvoltage threshold [PROJECT_DEFAULT]
    line_loading_max_pct: float = 100.0              # Nominal thermal limit threshold [MODEL_DERIVED / STANDARD_DERIVED]
    transformer_loading_max_pct: float = 100.0       # Nominal transformer rating threshold [MODEL_DERIVED]
    generator_p_tolerance_mw: float = 0.5            # Generator active power tolerance [PROJECT_DEFAULT]
    generator_q_tolerance_mvar: float = 0.5          # Generator reactive power tolerance [PROJECT_DEFAULT]


class PhysicsValidationResult(BaseModel):
    """
    Comprehensive physics validation outcome for an AC load flow solution.
    """
    is_valid: bool                                    # True if ALL physics and numerical constraints pass
    power_balance_valid: bool                         # System-level Active & Reactive power conservation law satisfied
    nodal_balance_valid: bool = True                  # Nodal KCL active power injection-flow equilibrium satisfied
    voltage_limits_valid: bool                        # All bus voltages within acceptable limits
    line_limits_valid: bool                           # All transmission lines operating within thermal limits
    transformer_limits_valid: bool                    # All transformers operating within rating & tap bounds
    generator_limits_valid: bool                      # All generators operating within P/Q capability curve
    numerical_valid: bool                             # No NaN, Inf, or unphysical values
    solver_converged: bool                            # Newton-Raphson non-linear AC power flow converged
    voltage_classification: str = VoltageClassification.NORMAL.value
    violated_buses: List[str] = Field(default_factory=list)
    minimum_bus_voltage: float = 1.0
    maximum_bus_voltage: float = 1.0
    violations: List[PhysicsViolationRecord] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)
    metrics: PhysicsValidationMetrics = Field(default_factory=PhysicsValidationMetrics)
    tolerances: PhysicsValidationTolerances = Field(default_factory=PhysicsValidationTolerances)
    provenance: str = "SOLVER_DERIVED"
    timestamp: str = Field(default_factory=lambda: datetime.utcnow().isoformat())
    simulation_id: Optional[str] = None
    cascade_id: Optional[str] = None


class PhysicsValidator:
    """
    Independent validation engine for AC power-flow states.
    Audits physical conservation laws and operating boundaries without altering solver results.
    """

    @classmethod
    def validate(
        cls,
        solver_result: PowerFlowResult,
        network_data: Optional[Dict[str, Any]] = None,
        tolerances: Optional[PhysicsValidationTolerances] = None,
        simulation_id: Optional[str] = None,
        cascade_id: Optional[str] = None,
        step: int = 0
    ) -> PhysicsValidationResult:
        """
        Performs full independent physics validation on a calculated electrical state.
        """
        tol = tolerances or PhysicsValidationTolerances()
        violations: List[PhysicsViolationRecord] = []
        warnings: List[str] = []

        # 1. Numerical Sanity & Solver Convergence Check
        solver_converged = (solver_result.status == "SUCCESS")
        numerical_valid = True

        if not solver_converged:
            violations.append(PhysicsViolationRecord(
                violation_type=PhysicsViolationType.SOLVER_DIVERGENCE.value,
                element_id=solver_result.network_id or "NETWORK",
                element_type="SYSTEM",
                observed_value=0.0,
                limit_value=1.0,
                violation_amount=1.0,
                unit="status",
                severity="CRITICAL",
                description=f"AC power-flow solver failed to reach convergence (status: {solver_result.status}).",
                step=step,
                simulation_id=simulation_id,
                cascade_id=cascade_id
            ))

        # Check for NaN / Inf in buses
        for bus in getattr(solver_result, "buses", []):
            v_pu = getattr(bus, "voltage_pu", 1.0)
            v_ang = getattr(bus, "voltage_angle_deg", 0.0)
            if math.isnan(v_pu) or math.isinf(v_pu) or math.isnan(v_ang) or math.isinf(v_ang):
                numerical_valid = False
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.NUMERICAL_INVALID_STATE.value,
                    element_id=bus.bus_id,
                    element_type="BUS",
                    observed_value=0.0 if math.isnan(v_pu) else 999.0,
                    limit_value=1.0,
                    violation_amount=1.0,
                    unit="pu",
                    severity="CRITICAL",
                    description=f"Bus {bus.bus_id} produced NaN/Inf voltage magnitude or angle.",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))

        # Check for NaN / Inf in lines
        for line in getattr(solver_result, "lines", []):
            loading = getattr(line, "loading_percent", 0.0)
            p_from = getattr(line, "p_from_mw", 0.0)
            if math.isnan(loading) or math.isinf(loading) or math.isnan(p_from) or math.isinf(p_from):
                numerical_valid = False
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.NUMERICAL_INVALID_STATE.value,
                    element_id=line.line_id,
                    element_type="LINE",
                    observed_value=0.0 if math.isnan(loading) else 999.0,
                    limit_value=100.0,
                    violation_amount=1.0,
                    unit="%",
                    severity="CRITICAL",
                    description=f"Line {line.line_id} produced NaN/Inf power flow or loading.",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))

        # Check for NaN / Inf in transformers
        for xfmr in getattr(solver_result, "transformers", []):
            loading = getattr(xfmr, "loading_percent", 0.0)
            p_hv = getattr(xfmr, "p_hv_mw", 0.0)
            if math.isnan(loading) or math.isinf(loading) or math.isnan(p_hv) or math.isinf(p_hv):
                numerical_valid = False
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.NUMERICAL_INVALID_STATE.value,
                    element_id=xfmr.transformer_id,
                    element_type="TRANSFORMER",
                    observed_value=0.0 if math.isnan(loading) else 999.0,
                    limit_value=100.0,
                    violation_amount=1.0,
                    unit="%",
                    severity="CRITICAL",
                    description=f"Transformer {xfmr.transformer_id} produced NaN/Inf power flow or loading.",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))

        # 2. Power Conservation / KCL Balance Check
        power_balance_valid = True
        gen_p = 0.0
        load_p = 0.0
        losses_p = 0.0
        p_error = 0.0

        gen_q = 0.0
        load_q = 0.0
        losses_q = 0.0
        q_error = 0.0

        if solver_result.power_balance:
            pb = solver_result.power_balance
            gen_p = getattr(pb, "total_generation_mw", 0.0)
            load_p = getattr(pb, "total_load_mw", 0.0)
            losses_p = getattr(pb, "total_losses_mw", getattr(pb, "losses_mw", 0.0))
            p_error = abs(gen_p - (load_p + losses_p))

            gen_q = getattr(pb, "total_q_generation_mvar", 0.0)
            load_q = getattr(pb, "total_q_load_mvar", 0.0)
            losses_q = getattr(pb, "total_q_losses_mvar", 0.0)
            q_error = abs(gen_q - (load_q + losses_q))

            if p_error > tol.active_power_balance_tol_mw:
                power_balance_valid = False
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.POWER_BALANCE_VIOLATION.value,
                    element_id=solver_result.network_id or "GRID",
                    element_type="SYSTEM",
                    observed_value=round(p_error, 3),
                    limit_value=tol.active_power_balance_tol_mw,
                    violation_amount=round(p_error - tol.active_power_balance_tol_mw, 3),
                    unit="MW",
                    severity="CRITICAL" if p_error > 10.0 else "WARNING",
                    description=f"Active power conservation mismatch: |{gen_p:.2f} - ({load_p:.2f} + {losses_p:.2f})| = {p_error:.3f} MW exceeds {tol.active_power_balance_tol_mw} MW tolerance.",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))

            if q_error > tol.reactive_power_balance_tol_mvar:
                power_balance_valid = False
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.POWER_BALANCE_VIOLATION.value,
                    element_id=solver_result.network_id or "GRID",
                    element_type="SYSTEM",
                    observed_value=round(q_error, 3),
                    limit_value=tol.reactive_power_balance_tol_mvar,
                    violation_amount=round(q_error - tol.reactive_power_balance_tol_mvar, 3),
                    unit="MVAr",
                    severity="WARNING",
                    description=f"Reactive power conservation mismatch: |{gen_q:.2f} - ({load_q:.2f} + {losses_q:.2f})| = {q_error:.3f} MVAr exceeds {tol.reactive_power_balance_tol_mvar} MVAr tolerance.",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))
        # 2b. Nodal Balance / KCL Check (Active and Reactive)
        nodal_balance_valid = True
        max_nodal_p_residual = 0.0
        max_nodal_q_residual = 0.0
        bus_p_injections = {}
        bus_q_injections = {}
        for b in getattr(solver_result, "buses", []):
            p_inj = getattr(b, "p_gen_mw", 0.0) - getattr(b, "p_load_mw", 0.0)
            q_inj = getattr(b, "q_gen_mvar", 0.0) - getattr(b, "q_load_mvar", 0.0)
            bus_p_injections[b.bus_id] = p_inj
            bus_q_injections[b.bus_id] = q_inj

        bus_branch_p_flows: Dict[str, float] = {b.bus_id: 0.0 for b in getattr(solver_result, "buses", [])}
        bus_branch_q_flows: Dict[str, float] = {b.bus_id: 0.0 for b in getattr(solver_result, "buses", [])}
        has_branch_flows = False

        for line in getattr(solver_result, "lines", []):
            if getattr(line, "p_from_mw", None) is not None and line.from_bus in bus_branch_p_flows:
                bus_branch_p_flows[line.from_bus] += line.p_from_mw
                has_branch_flows = True
            if getattr(line, "p_to_mw", None) is not None and line.to_bus in bus_branch_p_flows:
                bus_branch_p_flows[line.to_bus] += line.p_to_mw
                has_branch_flows = True
            if getattr(line, "q_from_mvar", None) is not None and line.from_bus in bus_branch_q_flows:
                bus_branch_q_flows[line.from_bus] += line.q_from_mvar
            if getattr(line, "q_to_mvar", None) is not None and line.to_bus in bus_branch_q_flows:
                bus_branch_q_flows[line.to_bus] += line.q_to_mvar

        for xfmr in getattr(solver_result, "transformers", []):
            if getattr(xfmr, "p_hv_mw", None) is not None and xfmr.from_bus in bus_branch_p_flows:
                bus_branch_p_flows[xfmr.from_bus] += xfmr.p_hv_mw
                has_branch_flows = True
            if getattr(xfmr, "p_lv_mw", None) is not None and xfmr.to_bus in bus_branch_p_flows:
                bus_branch_p_flows[xfmr.to_bus] += xfmr.p_lv_mw
                has_branch_flows = True
            if getattr(xfmr, "q_hv_mvar", None) is not None and xfmr.from_bus in bus_branch_q_flows:
                bus_branch_q_flows[xfmr.from_bus] += xfmr.q_hv_mvar
            if getattr(xfmr, "q_lv_mvar", None) is not None and xfmr.to_bus in bus_branch_q_flows:
                bus_branch_q_flows[xfmr.to_bus] += xfmr.q_lv_mvar

        if has_branch_flows:
            for bus_id, p_inj in bus_p_injections.items():
                flow_p_sum = bus_branch_p_flows.get(bus_id, 0.0)
                residual_p = abs(p_inj - flow_p_sum)
                if residual_p > max_nodal_p_residual:
                    max_nodal_p_residual = residual_p
                if residual_p > tol.nodal_p_balance_tol_mw:
                    nodal_balance_valid = False
                    violations.append(PhysicsViolationRecord(
                        violation_type=PhysicsViolationType.POWER_BALANCE_VIOLATION.value,
                        element_id=bus_id,
                        element_type="BUS",
                        observed_value=round(residual_p, 3),
                        limit_value=tol.nodal_p_balance_tol_mw,
                        violation_amount=round(residual_p - tol.nodal_p_balance_tol_mw, 3),
                        unit="MW",
                        severity="WARNING",
                        threshold_source=ThresholdSource.PROJECT_DEFAULT.value,
                        rule_name="NODAL_ACTIVE_POWER_BALANCE",
                        description=f"Bus {bus_id} nodal KCL mismatch: |Injected ({p_inj:.2f}) - BranchFlows ({flow_p_sum:.2f})| = {residual_p:.3f} MW exceeds {tol.nodal_p_balance_tol_mw} MW tolerance.",
                        step=step,
                        simulation_id=simulation_id,
                        cascade_id=cascade_id
                    ))

                # Reactive nodal balance
                q_inj = bus_q_injections.get(bus_id, 0.0)
                flow_q_sum = bus_branch_q_flows.get(bus_id, 0.0)
                residual_q = abs(q_inj - flow_q_sum)
                if residual_q > max_nodal_q_residual:
                    max_nodal_q_residual = residual_q
                if residual_q > tol.nodal_q_balance_tol_mvar:
                    nodal_balance_valid = False
                    violations.append(PhysicsViolationRecord(
                        violation_type=PhysicsViolationType.POWER_BALANCE_VIOLATION.value,
                        element_id=bus_id,
                        element_type="BUS",
                        observed_value=round(residual_q, 3),
                        limit_value=tol.nodal_q_balance_tol_mvar,
                        violation_amount=round(residual_q - tol.nodal_q_balance_tol_mvar, 3),
                        unit="MVAr",
                        severity="WARNING",
                        threshold_source=ThresholdSource.PROJECT_DEFAULT.value,
                        rule_name="NODAL_REACTIVE_POWER_BALANCE",
                        description=f"Bus {bus_id} nodal reactive KCL mismatch: |Injected ({q_inj:.2f}) - BranchFlows ({flow_q_sum:.2f})| = {residual_q:.3f} MVAr exceeds {tol.nodal_q_balance_tol_mvar} MVAr tolerance.",
                        step=step,
                        simulation_id=simulation_id,
                        cascade_id=cascade_id
                    ))

        # 3. Voltage Limits Validation
        voltage_limits_valid = True
        violated_buses: List[str] = []
        voltage_classification = VoltageClassification.NORMAL.value
        bus_voltages = [b.voltage_pu for b in getattr(solver_result, "buses", []) if hasattr(b, "voltage_pu")]
        min_v = min(bus_voltages) if bus_voltages else 1.0
        max_v = max(bus_voltages) if bus_voltages else 1.0

        for bus in getattr(solver_result, "buses", []):
            v = bus.voltage_pu
            if v < tol.voltage_min_critical_pu:
                voltage_limits_valid = False
                violated_buses.append(bus.bus_id)
                voltage_classification = VoltageClassification.CRITICAL_VOLTAGE.value
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.VOLTAGE_UNDERVOLTAGE.value,
                    element_id=bus.bus_id,
                    element_type="BUS",
                    observed_value=round(v, 4),
                    limit_value=tol.voltage_min_nominal_pu,
                    violation_amount=round(tol.voltage_min_nominal_pu - v, 4),
                    unit="pu",
                    severity="CRITICAL",
                    threshold_source=ThresholdSource.PROJECT_DEFAULT.value,
                    rule_name="BUS_CRITICAL_UNDERVOLTAGE",
                    description=f"Severe undervoltage on bus {bus.bus_id}: {v:.4f} pu (critical threshold < {tol.voltage_min_critical_pu} pu).",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))
            elif v < tol.voltage_min_nominal_pu:
                voltage_limits_valid = False
                violated_buses.append(bus.bus_id)
                if voltage_classification != VoltageClassification.CRITICAL_VOLTAGE.value:
                    voltage_classification = VoltageClassification.VOLTAGE_VIOLATION.value
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.VOLTAGE_UNDERVOLTAGE.value,
                    element_id=bus.bus_id,
                    element_type="BUS",
                    observed_value=round(v, 4),
                    limit_value=tol.voltage_min_nominal_pu,
                    violation_amount=round(tol.voltage_min_nominal_pu - v, 4),
                    unit="pu",
                    severity="WARNING",
                    threshold_source=ThresholdSource.STANDARD_DERIVED.value,
                    rule_name="BUS_NOMINAL_UNDERVOLTAGE",
                    description=f"Undervoltage on bus {bus.bus_id}: {v:.4f} pu (< {tol.voltage_min_nominal_pu} pu).",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))
            elif v > tol.voltage_max_critical_pu:
                voltage_limits_valid = False
                violated_buses.append(bus.bus_id)
                voltage_classification = VoltageClassification.CRITICAL_VOLTAGE.value
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.VOLTAGE_OVERVOLTAGE.value,
                    element_id=bus.bus_id,
                    element_type="BUS",
                    observed_value=round(v, 4),
                    limit_value=tol.voltage_max_nominal_pu,
                    violation_amount=round(v - tol.voltage_max_nominal_pu, 4),
                    unit="pu",
                    severity="CRITICAL",
                    threshold_source=ThresholdSource.PROJECT_DEFAULT.value,
                    rule_name="BUS_CRITICAL_OVERVOLTAGE",
                    description=f"Severe overvoltage on bus {bus.bus_id}: {v:.4f} pu (critical threshold > {tol.voltage_max_critical_pu} pu).",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))
            elif v > tol.voltage_max_nominal_pu:
                voltage_limits_valid = False
                violated_buses.append(bus.bus_id)
                if voltage_classification != VoltageClassification.CRITICAL_VOLTAGE.value:
                    voltage_classification = VoltageClassification.VOLTAGE_VIOLATION.value
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.VOLTAGE_OVERVOLTAGE.value,
                    element_id=bus.bus_id,
                    element_type="BUS",
                    observed_value=round(v, 4),
                    limit_value=tol.voltage_max_nominal_pu,
                    violation_amount=round(v - tol.voltage_max_nominal_pu, 4),
                    unit="pu",
                    severity="WARNING",
                    threshold_source=ThresholdSource.STANDARD_DERIVED.value,
                    rule_name="BUS_NOMINAL_OVERVOLTAGE",
                    description=f"Overvoltage on bus {bus.bus_id}: {v:.4f} pu (> {tol.voltage_max_nominal_pu} pu).",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))

        # 4. Transmission Line Thermal Limits Validation
        line_limits_valid = True
        active_lines = [l for l in getattr(solver_result, "lines", []) if getattr(l, "status", "IN_SERVICE") not in ("OUT_OF_SERVICE", "DISCONNECTED", "TRIPPED")]
        line_loadings = [l.loading_percent for l in active_lines if hasattr(l, "loading_percent")]
        max_line_loading = max(line_loadings) if line_loadings else 0.0

        for line in active_lines:
            loading = line.loading_percent
            if loading > tol.line_loading_max_pct:
                line_limits_valid = False
                excess = loading - tol.line_loading_max_pct
                severity = "CRITICAL" if loading >= 130.0 else "WARNING"
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.LINE_THERMAL_LIMIT.value,
                    element_id=line.line_id,
                    element_type="LINE",
                    observed_value=round(loading, 2),
                    limit_value=tol.line_loading_max_pct,
                    violation_amount=round(excess, 2),
                    unit="%",
                    severity=severity,
                    threshold_source=ThresholdSource.MODEL_DERIVED.value,
                    rule_name="LINE_THERMAL_RATING_LIMIT",
                    description=f"Transmission line {line.line_id} thermal overload: {loading:.2f}% (exceeds {tol.line_loading_max_pct}% rating by {excess:.2f}%).",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))

        # 5. Transformer Rating and Tap Position Validation
        transformer_limits_valid = True
        active_xfmrs = [t for t in getattr(solver_result, "transformers", []) if getattr(t, "status", "IN_SERVICE") not in ("OUT_OF_SERVICE", "DISCONNECTED", "TRIPPED")]
        xfmr_loadings = [t.loading_percent for t in active_xfmrs if hasattr(t, "loading_percent")]
        max_xfmr_loading = max(xfmr_loadings) if xfmr_loadings else 0.0

        for xfmr in active_xfmrs:
            loading = xfmr.loading_percent
            if loading > tol.transformer_loading_max_pct:
                transformer_limits_valid = False
                excess = loading - tol.transformer_loading_max_pct
                severity = "CRITICAL" if loading >= 130.0 else "WARNING"
                violations.append(PhysicsViolationRecord(
                    violation_type=PhysicsViolationType.TRANSFORMER_LIMIT.value,
                    element_id=xfmr.transformer_id,
                    element_type="TRANSFORMER",
                    observed_value=round(loading, 2),
                    limit_value=tol.transformer_loading_max_pct,
                    violation_amount=round(excess, 2),
                    unit="%",
                    severity=severity,
                    threshold_source=ThresholdSource.MODEL_DERIVED.value,
                    rule_name="TRANSFORMER_MVA_RATING_LIMIT",
                    description=f"Transformer {xfmr.transformer_id} overload: {loading:.2f}% (exceeds {tol.transformer_loading_max_pct}% rating by {excess:.2f}%).",
                    step=step,
                    simulation_id=simulation_id,
                    cascade_id=cascade_id
                ))

            # Tap validation if tap limits present
            tap_pos = getattr(xfmr, "tap_position", None)
            tap_min = getattr(xfmr, "tap_min", None)
            tap_max = getattr(xfmr, "tap_max", None)
            if tap_pos is not None and tap_min is not None and tap_max is not None:
                if tap_pos < tap_min or tap_pos > tap_max:
                    transformer_limits_valid = False
                    violations.append(PhysicsViolationRecord(
                        violation_type=PhysicsViolationType.TRANSFORMER_TAP_INVALID.value,
                        element_id=xfmr.transformer_id,
                        element_type="TRANSFORMER",
                        observed_value=float(tap_pos),
                        limit_value=float(tap_max if tap_pos > tap_max else tap_min),
                        violation_amount=float(abs(tap_pos - (tap_max if tap_pos > tap_max else tap_min))),
                        unit="tap_step",
                        severity="WARNING",
                        threshold_source=ThresholdSource.MODEL_DERIVED.value,
                        rule_name="TRANSFORMER_TAP_LIMIT",
                        description=f"Transformer {xfmr.transformer_id} invalid tap position {tap_pos} (allowed range: [{tap_min}, {tap_max}]).",
                        step=step,
                        simulation_id=simulation_id,
                        cascade_id=cascade_id
                    ))

        # 6. Generator Active & Reactive Output Limits Validation
        generator_limits_valid = True
        gens_to_check: List[Any] = []
        if getattr(solver_result, "generators", None):
            gens_to_check.extend(solver_result.generators)
        elif network_data and "generators" in network_data:
            gens = network_data.get("generators", [])
            if isinstance(gens, dict):
                gens_to_check.extend(gens.values())
            elif isinstance(gens, list):
                gens_to_check.extend(gens)

        bus_map = {b.bus_id: b for b in getattr(solver_result, "buses", [])}

        for gen in gens_to_check:
            gen_id = getattr(gen, "generator_id", "GEN_UNKNOWN")
            bus_id = getattr(gen, "bus_id", None)
            p_max = getattr(gen, "Pmax", getattr(gen, "p_max_mw", None))
            p_min = getattr(gen, "Pmin", getattr(gen, "p_min_mw", None))
            q_max = getattr(gen, "Qmax", getattr(gen, "q_max_mvar", None))
            q_min = getattr(gen, "Qmin", getattr(gen, "q_min_mvar", None))

            # Determine actual P and Q
            actual_p = getattr(gen, "current_P", None)
            actual_q = getattr(gen, "current_Q", None)

            if actual_p is None and bus_id and bus_id in bus_map:
                actual_p = bus_map[bus_id].p_gen_mw
            if actual_q is None and bus_id and bus_id in bus_map:
                actual_q = bus_map[bus_id].q_gen_mvar

            if actual_p is not None:
                if p_max is not None:
                    if actual_p > (p_max + tol.generator_p_tolerance_mw):
                        generator_limits_valid = False
                        excess = actual_p - p_max
                        violations.append(PhysicsViolationRecord(
                            violation_type=PhysicsViolationType.GENERATOR_P_LIMIT.value,
                            element_id=gen_id,
                            element_type="GENERATOR",
                            observed_value=round(actual_p, 2),
                            limit_value=float(p_max),
                            violation_amount=round(excess, 2),
                            unit="MW",
                            severity="CRITICAL" if excess > 20.0 else "WARNING",
                            threshold_source=ThresholdSource.MODEL_DERIVED.value,
                            rule_name="GENERATOR_PMAX_LIMIT",
                            description=f"Generator {gen_id} active power {actual_p:.2f} MW exceeds Pmax ({p_max:.2f} MW) by {excess:.2f} MW.",
                            step=step,
                            simulation_id=simulation_id,
                            cascade_id=cascade_id
                        ))
                else:
                    warnings.append(f"Generator {gen_id} Pmax NOT_AVAILABLE.")

                if p_min is not None:
                    if actual_p < (p_min - tol.generator_p_tolerance_mw):
                        generator_limits_valid = False
                        deficit = p_min - actual_p
                        violations.append(PhysicsViolationRecord(
                            violation_type=PhysicsViolationType.GENERATOR_P_LIMIT.value,
                            element_id=gen_id,
                            element_type="GENERATOR",
                            observed_value=round(actual_p, 2),
                            limit_value=float(p_min),
                            violation_amount=round(deficit, 2),
                            unit="MW",
                            severity="WARNING",
                            threshold_source=ThresholdSource.MODEL_DERIVED.value,
                            rule_name="GENERATOR_PMIN_LIMIT",
                            description=f"Generator {gen_id} active power {actual_p:.2f} MW below Pmin ({p_min:.2f} MW) by {deficit:.2f} MW.",
                            step=step,
                            simulation_id=simulation_id,
                            cascade_id=cascade_id
                        ))
                else:
                    warnings.append(f"Generator {gen_id} Pmin NOT_AVAILABLE.")

            if actual_q is not None:
                if q_max is not None:
                    if actual_q > (q_max + tol.generator_q_tolerance_mvar):
                        generator_limits_valid = False
                        excess = actual_q - q_max
                        violations.append(PhysicsViolationRecord(
                            violation_type=PhysicsViolationType.GENERATOR_Q_LIMIT.value,
                            element_id=gen_id,
                            element_type="GENERATOR",
                            observed_value=round(actual_q, 2),
                            limit_value=float(q_max),
                            violation_amount=round(excess, 2),
                            unit="MVAr",
                            severity="WARNING",
                            threshold_source=ThresholdSource.MODEL_DERIVED.value,
                            rule_name="GENERATOR_QMAX_LIMIT",
                            description=f"Generator {gen_id} reactive power {actual_q:.2f} MVAr exceeds Qmax ({q_max:.2f} MVAr) by {excess:.2f} MVAr.",
                            step=step,
                            simulation_id=simulation_id,
                            cascade_id=cascade_id
                        ))
                else:
                    warnings.append(f"Generator {gen_id} Qmax NOT_AVAILABLE.")

                if q_min is not None:
                    if actual_q < (q_min - tol.generator_q_tolerance_mvar):
                        generator_limits_valid = False
                        deficit = q_min - actual_q
                        violations.append(PhysicsViolationRecord(
                            violation_type=PhysicsViolationType.GENERATOR_Q_LIMIT.value,
                            element_id=gen_id,
                            element_type="GENERATOR",
                            observed_value=round(actual_q, 2),
                            limit_value=float(q_min),
                            violation_amount=round(deficit, 2),
                            unit="MVAr",
                            severity="WARNING",
                            threshold_source=ThresholdSource.MODEL_DERIVED.value,
                            rule_name="GENERATOR_QMIN_LIMIT",
                            description=f"Generator {gen_id} reactive power {actual_q:.2f} MVAr below Qmin ({q_min:.2f} MVAr) by {deficit:.2f} MVAr.",
                            step=step,
                            simulation_id=simulation_id,
                            cascade_id=cascade_id
                        ))
                else:
                    warnings.append(f"Generator {gen_id} Qmin NOT_AVAILABLE.")

        # 7. Compile Final Status
        is_valid = (
            solver_converged
            and numerical_valid
            and power_balance_valid
            and nodal_balance_valid
            and voltage_limits_valid
            and line_limits_valid
            and transformer_limits_valid
            and generator_limits_valid
        )

        metrics = PhysicsValidationMetrics(
            total_generation_p_mw=round(gen_p, 2),
            total_load_p_mw=round(load_p, 2),
            total_losses_p_mw=round(losses_p, 2),
            active_power_balance_error_mw=round(p_error, 3),
            system_active_balance_residual=round(p_error, 3),
            total_generation_q_mvar=round(gen_q, 2),
            total_load_q_mvar=round(load_q, 2),
            total_losses_q_mvar=round(losses_q, 2),
            reactive_power_balance_error_mvar=round(q_error, 3),
            system_reactive_balance_residual=round(q_error, 3),
            max_line_loading_pct=round(max_line_loading, 2),
            max_transformer_loading_pct=round(max_xfmr_loading, 2),
            min_bus_voltage_pu=round(min_v, 4),
            max_bus_voltage_pu=round(max_v, 4),
            max_nodal_p_residual_mw=round(max_nodal_p_residual, 3),
            maximum_nodal_p_residual=round(max_nodal_p_residual, 3),
            maximum_nodal_q_residual=round(max_nodal_q_residual, 3),
            voltage_classification=voltage_classification,
            violated_buses=list(set(violated_buses)),
            active_power_balance_passed=(p_error <= tol.active_power_balance_tol_mw),
            reactive_power_balance_passed=(q_error <= tol.reactive_power_balance_tol_mvar),
            nodal_balance_passed=nodal_balance_valid
        )

        return PhysicsValidationResult(
            is_valid=is_valid,
            power_balance_valid=power_balance_valid,
            nodal_balance_valid=nodal_balance_valid,
            voltage_limits_valid=voltage_limits_valid,
            line_limits_valid=line_limits_valid,
            transformer_limits_valid=transformer_limits_valid,
            generator_limits_valid=generator_limits_valid,
            numerical_valid=numerical_valid,
            solver_converged=solver_converged,
            voltage_classification=voltage_classification,
            violated_buses=list(set(violated_buses)),
            minimum_bus_voltage=round(min_v, 4),
            maximum_bus_voltage=round(max_v, 4),
            violations=violations,
            warnings=warnings,
            metrics=metrics,
            tolerances=tol,
            provenance="SOLVER_DERIVED",
            simulation_id=simulation_id,
            cascade_id=cascade_id
        )


